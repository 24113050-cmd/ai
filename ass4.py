rules=[
    ({"yellow_leaves","wilting"},"root_rot"),
    ({"dry_soil","wilting"},"water_def"),
    ({"brown_spots","yellow_leaves"},"leaf_spot")
]
def forward_chaining():
  facts=set()
  n = int(input("enter number of facts"))
  for i in range (n):
    fact=input("enter fact")
    facts.add(fact)

  while True:
    new=False

    for condition,conclusion in rules:
      if condition.issubset(facts) and conclusion not in facts:
        facts.add(conclusion)
        print("new conclusion",conclusion)
        new = True

    if not new:
      break

  print("\nAll facts:", facts)

def backward_chaining():
  facts=set()
  n = int(input("enter number of facts"))
  for i in range (n):
    fact=input("enter fact")
    facts.add(fact)

  goal = input("enter goal to prove")

  def prove(goal):
    if goal in facts:
      return True
    for condition,conclusion in rules:
      if goal==conclusion:
        for fact in condition:
          if not prove(fact):
            return False
        return True
    return


  if prove(goal):
    print("Goal proved:", goal)
  else:
    print("Goal cannot be proved:", goal)

backward_chaining()